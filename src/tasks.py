"""
Task 定义模块

定义旅行规划系统中的所有 Task，每个 Task 绑定到特定 Agent。
支持通过 {variable} 占位符接收动态输入（目的地、天数、预算等）。
"""
from crewai import Task

from agents import (
    researcher,
    hotel_planner,
    transport_planner,
    itinerary_planner,
    budget_analyst,
)


# ---------------------------------------------------------------------------
# 目的地信息调研任务
# ---------------------------------------------------------------------------
research_task = Task(
    description=(
        "搜索目的地「{destination}」的以下信息并整理成结构化报告：\n"
        "1. **必去景点**（5-8个，附门票参考价、简要介绍和推荐理由）\n"
        "2. **当地美食**（5-8种，附人均消费参考和推荐餐厅或区域）\n"
        "3. **特色文化活动**（季节性活动、节日等，附参考价格）\n"
        "4. **购物推荐**（主要商业区/特色店铺，附消费参考）\n"
        "5. **最佳旅行季节**和气温提示"
    ),
    expected_output=(
        "一份按类别（景点/美食/活动/购物）整理的信息清单，"
        "每个项目包含名称、简要说明和参考价格"
    ),
    agent=researcher,
)

# ---------------------------------------------------------------------------
# 住宿推荐任务
# ---------------------------------------------------------------------------
hotel_task = Task(
    description=(
        "搜索{destination}的住宿推荐，覆盖以下价位：\n"
        "1. **经济型**（预算 300-600 元/晚）—— 1-2 个推荐\n"
        "2. **舒适型**（预算 600-1200 元/晚）—— 1-2 个推荐\n"
        "3. **豪华型**（预算 1200+ 元/晚）—— 1 个推荐\n\n"
        "每个推荐需包含：酒店名称、大致位置、特色亮点、预估每晚价格。"
    ),
    expected_output=(
        "一份按价位分组的住宿推荐列表，包含酒店名称、位置和价格范围"
    ),
    agent=hotel_planner,
)

# ---------------------------------------------------------------------------
# 交通规划任务
# ---------------------------------------------------------------------------
transport_task = Task(
    description=(
        "规划从「{departure}」到「{destination}」的交通方案，包括：\n"
        "1. **国际交通**：推荐航班方案（直飞/转机、航司、参考价格）\n"
        "2. **机场到市区**：机场快线/巴士/出租车等选项及费用\n"
        "3. **市内交通**：地铁/JR Pass/打车/公交的建议及日均费用\n"
        "4. **交通周游券**：是否值得购买通票及节省金额"
    ),
    expected_output=(
        "一份完整的交通方案说明，包含国际航班建议、机场交通、"
        "市内交通和优惠通票推荐，标注各项费用"
    ),
    agent=transport_planner,
)

# ---------------------------------------------------------------------------
# 行程整合任务
# ---------------------------------------------------------------------------
itinerary_task = Task(
    description=(
        "综合以上所有调研结果（景点、美食、住宿、交通），"
        "制定一份 **{days} 日 {destination} 旅行计划**，要求：\n"
        "1. **每日行程**：每天安排 3-4 个活动，标注地点、大致时间和预估花费\n"
        "2. **住宿安排**：推荐全程同一家酒店或分区换住，标注总价\n"
        "3. **美食推荐**：每日推荐 1-2 个餐厅或美食体验，标注人均\n"
        "4. **预算估算**：列出交通、住宿、餐饮、门票、购物等各项预估总花费\n"
        "5. **实用贴士**：签证、网络、语言、支付方式等"
    ),
    expected_output=(
        "一份结构清晰的 {days} 日 {destination} 旅行规划书，包含每日行程表、"
        "住宿推荐、交通方案、预算明细和实用贴士"
    ),
    agent=itinerary_planner,
)

# ---------------------------------------------------------------------------
# 预算分析任务
# 基于其他 Agent 的输出，按用户预算做分配方案
# ---------------------------------------------------------------------------
budget_task = Task(
    description=(
        "你是一名预算分析师。用户总预算为 **{budget} 元**，旅行 {days} 天，"
        "目的地 {destination}。\n\n"
        "请参考以下其他专家提供的详细信息，制定精确的预算分配方案：\n"
        "- 景点门票及活动费用（来自调研报告）\n"
        "- 住宿费用（来自住宿推荐）\n"
        "- 交通费用含机票和市内交通（来自交通方案）\n"
        "- 行程安排涉及的其他开销（来自行程计划）\n\n"
        "请按以下结构输出：\n"
        "1. **预算总览**：总预算 vs 预估总花费，标注结余或超支金额\n"
        "2. **分项预算表**：按 交通 / 住宿 / 餐饮 / 门票 / 购物 / 其他 分类，"
        "每项含推荐预算金额、实际预估、差额和说明\n"
        "3. **每日平均花费**：总花费 ÷ {days} 天\n"
        "4. **省钱建议**：3-5 条针对该目的地的具体省钱技巧\n"
        "5. **调整建议**：如果超支，建议削减哪些项目；如果有结余，建议加在哪些项目上"
    ),
    expected_output=(
        "一份完整的预算分析报告，包含预算总览表、分项预算明细、"
        "每日平均花费、省钱建议和调整建议"
    ),
    agent=budget_analyst,
    context=[research_task, hotel_task, transport_task, itinerary_task],
)

__all__ = [
    "research_task",
    "hotel_task",
    "transport_task",
    "itinerary_task",
    "budget_task",
]
